const {chromium} = require(process.env.CODEX_PRIMARY_RUNTIME_NODE_MODULES ? process.env.CODEX_PRIMARY_RUNTIME_NODE_MODULES + '/playwright' : 'playwright');
const fs = require('fs');
(async () => {
 const browser = await chromium.launch({headless:true, executablePath: process.env.SONGCHEON_TEST_BROWSER || undefined});
 const page = await browser.newPage();
 let html = fs.readFileSync('src/main/resources/templates/daily-entry.html','utf8').replace(/<script[\s\S]*?<\/script>/g,'');
 html = html.replace('data-entry-row th:attr="data-entry-sequence=${row.sequence}"','data-entry-row data-entry-sequence="1"');
 await page.setContent(html);
 for (const name of ['app', 'daily-entry']) await page.addStyleTag({path:`src/main/resources/static/css/${name}.css`});
 await page.evaluate(() => {
  const row = document.querySelector('[data-entry-row]');
  row.querySelector('[name="vendorName"]').value = '거래처A';
  row.querySelector('[name="regular"]').value = '12';
  const second = row.cloneNode(true); second.dataset.entrySequence = '2';
  second.querySelector('[name="vendorName"]').value = '거래처B';
  second.querySelector('[name="regular"]').value = '34'; row.parentNode.append(second);
  const third = second.cloneNode(true); third.dataset.entrySequence = '3'; third.querySelector('[name="vendorName"]').value = '거래처C'; third.querySelector('[name="regular"]').value = '56'; row.parentNode.append(third);
  document.querySelector('meta[name="_csrf"]').content = 'test';
  document.querySelector('meta[name="_csrf_header"]').content = 'X-CSRF-TOKEN';
  window.dailyEntryLayout = {};
  window.fetch = async (url, options) => {window.layoutSent=JSON.parse(options.body); return {ok:true, redirected:false};};
 });
 await page.addScriptTag({path:'src/main/resources/static/js/daily-entry-layout.js'});
 await page.addScriptTag({path:'src/main/resources/static/js/daily-entry.js'});
 await page.locator('[data-layout-edit]').click();
 await page.getByRole('button',{name:'거래처A 아래로',exact:true}).click();
 let order = await page.locator('[data-entry-row]').evaluateAll(rows=>rows.map(r=>r.dataset.entrySequence));
 if(order.join() !== '2,1,3') throw Error('row movement failed');
 await page.getByRole('button',{name:'거래처A 삭제',exact:true}).click();
 await page.locator('[data-layout-products] .entry-layout-item').first().getByRole('button',{name:/뒤로/}).click();
 await page.locator('[data-layout-products] .entry-layout-item').first().getByRole('button',{name:/삭제/}).click();
 await page.locator('[data-layout-save]').click();
 await page.waitForFunction(()=>document.querySelector('[data-layout-editor]').hidden);
 await page.locator('[data-entry-sequence="2"] [name="tofu"]').focus();
 await page.keyboard.press('Enter');
 if(await page.evaluate(()=>document.activeElement.closest('tr').dataset.entrySequence) !== '3') throw Error('Enter did not skip hidden vendor');
 const outcome = await page.evaluate(()=> {
  const form = document.querySelector('[data-daily-entry-form]');
  const event = new Event('submit', {cancelable:true}); form.dispatchEvent(event);
  const data = new FormData(form);
  return {names:data.getAll('vendorName'), regular:data.getAll('regular'), layout:window.layoutSent};
 });
 if(outcome.names.join() !== '거래처A,거래처B,거래처C' || outcome.regular.join() !== '12,34,56') throw Error('saved sales mapping changed');
 if(outcome.layout.hiddenVendors.join()!=='1' || outcome.layout.hiddenProducts.join()!=='regular') throw Error('layout save failed');
 await page.locator('[data-layout-edit]').click();
 await page.locator('[data-layout-reset]').click();
 await page.locator('[data-layout-cancel]').click();
 if(await page.locator('[data-entry-sequence="1"]').evaluate(r=>!r.classList.contains('entry-layout-hidden'))) throw Error('cancel failed');
 await page.setViewportSize({width:390,height:844});
 if(await page.locator('[data-entry-sequence="1"]').isVisible()) throw Error('hidden row visible on mobile');
 if(await page.locator('[data-entry-sequence="2"] [name="regular"]').isVisible()) throw Error('hidden column visible on mobile');
 await page.locator('[data-layout-edit]').click();
 await page.locator('[data-layout-reset]').click();
 await page.evaluate(()=> {window.fetch = async () => ({ok:false});});
 await page.locator('[data-layout-save]').click();
 await page.waitForFunction(()=>document.querySelector('[data-layout-status]').textContent.includes('저장하지 못했습니다'));
 if(await page.locator('[data-layout-editor]').isHidden()) throw Error('failed save dismissed editor');
 await page.locator('[data-layout-cancel]').click();
 const savedLayout = await page.evaluate(()=>window.layoutSent);
 await page.evaluate(layout => {
   document.querySelectorAll('[data-entry-row]').forEach(row => row.classList.remove('entry-layout-hidden'));
   window.dailyEntryLayout = layout;
 }, savedLayout);
 await page.addScriptTag({path:'src/main/resources/static/js/daily-entry-layout.js'});
 if(await page.locator('[data-entry-sequence="1"]').isVisible()) throw Error('saved layout did not restore');
 console.log('PASS: row/column movement, deletion, save/cancel/reset, mobile visibility, Enter navigation, failure recovery, reload, and original sales payload');
 await browser.close();
})();
